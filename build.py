#!/usr/bin/env python3
"""Rebuild puzzles-data.js from schedule.json and sources/<set>/puzzles.json.

Days already shipped in puzzles-data.js that have no source file are kept, so a
rebuild does not drop puzzles whose authoring JSON was never committed. A puzzle
id that appears under sources/<set>/puzzles.json (or a root puzzles.json) is
taken from that file. schedule.json is copied into window.WIS_SCHEDULE.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "puzzles-data.js"
SCHEDULE = ROOT / "schedule.json"

COLS = [
    "puzzle_id", "daily_order", "round", "set", "placeholder", "practice_only",
    "featured_name", "featured_handle", "featured_ig_url", "featured_avatar", "featured_pronoun",
    "consent_on", "media_type", "image_url", "video_url", "poster_url", "lat", "lng",
    "place_name", "country", "fun_fact", "photo_date", "credit", "license", "license_url",
    "source_url", "focus", "focus_mobile", "in_frame",
]
BOOLS = {"placeholder", "practice_only", "in_frame"}


def load_generated():
    text = DATA.read_text()
    rows = json.loads(re.search(r"window\.WIS_PUZZLE_ROWS = (\[.*\]);", text, re.S).group(1))
    sched = json.loads(re.search(r"window\.WIS_SCHEDULE = (\{.*\});", text, re.S).group(1))
    build = json.loads(re.search(r"window\.WIS_BUILD = (\".*\");", text).group(1))
    return rows, sched, build


def as_rows(data):
    if isinstance(data, dict):
        data = data.get("rows") or data.get("puzzles") or []
    if not isinstance(data, list):
        raise SystemExit(f"puzzle file must be a list of rows, got {type(data).__name__}")
    return data


def normalize(row):
    out = {}
    for key in COLS:
        if key in row and row[key] is not None:
            out[key] = row[key]
        elif key in BOOLS:
            out[key] = False
        else:
            out[key] = ""
    return out


def load_json_rows(path):
    return [normalize(row) for row in as_rows(json.loads(path.read_text()))]


def set_rows():
    sources = ROOT / "sources"
    rows = []
    if sources.is_dir():
        for path in sorted(sources.glob("*/puzzles.json")):
            rows.extend(load_json_rows(path))
    return rows


def build():
    old_rows, old_sched, build_id = load_generated()
    schedule = json.loads(SCHEDULE.read_text()) if SCHEDULE.is_file() else old_sched
    incoming = set_rows()
    incoming_ids = {row["puzzle_id"] for row in incoming if row.get("puzzle_id")}
    root_json = ROOT / "puzzles.json"
    if root_json.is_file():
        root_rows = [row for row in load_json_rows(root_json) if row.get("puzzle_id") not in incoming_ids]
        base = root_rows + incoming
    else:
        # Keep shipped days that have no authoring file, then append source puzzles.
        base = [row for row in old_rows if row.get("puzzle_id") not in incoming_ids] + incoming
    text = (
        "// Generated by build.py from schedule.json + sources/<set>/puzzles.json"
        " (days already shipped without a source file are kept). Do not edit by hand.\n"
        f"window.WIS_PUZZLE_ROWS = {json.dumps(base, ensure_ascii=False, separators=(', ', ': '))};\n"
        f"window.WIS_SCHEDULE = {json.dumps(schedule, ensure_ascii=False, separators=(', ', ': '))};\n"
        "\n"
        f"window.WIS_BUILD = {json.dumps(build_id)};\n"
    )
    DATA.write_text(text)
    ids = []
    for row in base:
        if row["puzzle_id"] not in ids:
            ids.append(row["puzzle_id"])
    print(f"build.py: {len(base)} rows, {len(ids)} puzzles ({', '.join(ids)})")
    print(f"build.py: schedule pins {len(schedule.get('dates') or {})} dates, rotation {schedule.get('rotation')!r}")
    return base, schedule


if __name__ == "__main__":
    build()
